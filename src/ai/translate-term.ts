import "server-only";

import { and, asc, eq, isNull } from "drizzle-orm";
import { alias } from "drizzle-orm/pg-core";

import { db, type Explanation, explanations, posts, terms } from "@/db";
import { hasFrenchMarks, isWellMarked } from "@/lib/french-marks";

import { translateExplanation, translatePostText } from "./translate";

export type TranslateResult =
  | {
      ok: true;
      explanation: Explanation;
      /** The post text in French (8.3); null only if it couldn't be stored. */
      textFr: string | null;
      generated: boolean;
    }
  | { ok: false; reason: "missing" | "no-english" };

const fr = alias(explanations, "fr");

/**
 * The French explanation of one term (8.1, 8.2, D-09) and the French post
 * text with its marks (8.3, 8.4, D-18, E-07, E-08): served from the database
 * when they exist, otherwise generated by one Claude call #3 and stored. Only
 * terms of published posts are translated.
 *
 * The post text goes into the call while `posts.text_fr` has no marks: empty
 * (the post's first Translate: one call for the word and the text) or made
 * before 8.4 (regenerated once). When the word is already translated, that
 * regeneration is a call for the text alone; the word's explanation stays as
 * it is. Later words of a post whose text is marked are translated alone.
 * The word's row and the post's French text are written in one transaction.
 *
 * Two clicks at the same time can't store two versions: the UNIQUE
 * (term_id, language) constraint keeps the first explanation, and `text_fr`
 * is only replaced while it still holds the value that was read.
 */
export async function getOrCreateFrench(termId: string): Promise<TranslateResult> {
  const [row] = await db
    .select({
      postId: terms.postId,
      headword: terms.headword,
      text: posts.text,
      textFr: posts.textFr,
      english: explanations,
      french: fr,
    })
    .from(terms)
    .innerJoin(posts, and(eq(posts.id, terms.postId), eq(posts.status, "published")))
    .leftJoin(explanations, and(eq(explanations.termId, terms.id), eq(explanations.language, "en")))
    .leftJoin(fr, and(eq(fr.termId, terms.id), eq(fr.language, "fr")))
    .where(eq(terms.id, termId));

  if (!row) return { ok: false, reason: "missing" };

  // A text_fr stored before 8.4 has no marks. An empty one is made with the
  // first translated word, never alone.
  const unmarked = row.textFr !== null && !hasFrenchMarks(row.textFr);
  const needsText = row.textFr === null || unmarked;
  const text = row.text ?? "";

  if (row.french && !unmarked) {
    return { ok: true, explanation: row.french, textFr: row.textFr, generated: false };
  }
  const postTerms = needsText
    ? await db
        .select({ surface: terms.surface, headword: terms.headword })
        .from(terms)
        .where(eq(terms.postId, row.postId))
        .orderBy(asc(terms.position))
    : [];
  // Only while the stored value is the one that was read: a parallel click may have replaced it.
  const textFrIsUnchanged = and(
    eq(posts.id, row.postId),
    eq(posts.text, text),
    row.textFr === null ? isNull(posts.textFr) : eq(posts.textFr, row.textFr),
  );

  if (row.french) {
    // Translated before 8.4: only the text is regenerated.
    const { output } = await translatePostText({
      postId: row.postId,
      postText: text,
      terms: postTerms,
    });
    const marked = output.postTextFr.trim();
    if (isWellMarked(marked)) {
      await db.update(posts).set({ textFr: marked }).where(textFrIsUnchanged);
    }
  } else {
    const english = row.english;
    if (!english) return { ok: false, reason: "no-english" };
    const { output, model } = await translateExplanation({
      postId: row.postId,
      headword: row.headword,
      english,
      text: needsText ? { postText: text, terms: postTerms } : null,
    });
    const marked = output.postTextFr?.trim() ?? "";
    // No marks, or a stray one: keep what was stored (the next Translate tries again).
    const textFr = isWellMarked(marked) ? marked : row.textFr;

    await db.batch([
      db
        .insert(explanations)
        .values({
          termId,
          language: "fr",
          // Already French in the English row, and the same in both versions.
          frEquivalents: english.frEquivalents,
          definition: output.definition.trim(),
          analogyTitle: output.analogyTitle.trim(),
          analogyBody: output.analogyBody.trim(),
          analogyEmoji: english.analogyEmoji,
          // E-03: the question and the quote stay in English; the question gets its French version.
          exampleQuestion: english.exampleQuestion,
          exampleQuestionFr: output.exampleQuestionFr.trim(),
          inYourTextQuote: english.inYourTextQuote,
          inYourTextExplanation: output.inYourTextExplanation.trim(),
          model,
        })
        .onConflictDoNothing({ target: [explanations.termId, explanations.language] }),
      db.update(posts).set({ textFr }).where(textFrIsUnchanged),
    ]);
  }

  // Read back what is stored now: ours, or what a parallel request stored first.
  const [stored] = await db
    .select({ explanation: explanations, textFr: posts.textFr })
    .from(explanations)
    .innerJoin(terms, eq(terms.id, explanations.termId))
    .innerJoin(posts, eq(posts.id, terms.postId))
    .where(and(eq(explanations.termId, termId), eq(explanations.language, "fr")));
  if (!stored) return { ok: false, reason: "missing" };
  return {
    ok: true,
    explanation: stored.explanation,
    textFr: stored.textFr,
    generated: !row.french,
  };
}
