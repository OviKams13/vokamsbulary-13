"use client";

import { type TouchEvent, useRef, useState, useTransition } from "react";

import { Explanation, ExplanationHeader } from "@/components/explanation";
import { NumberedListIcon } from "@/components/icons";
import type { Explanation as ExplanationRow } from "@/db/schema";

import { translateAction } from "./actions";
import { ExamplesView } from "./examples-view";
import { usePostTranslation } from "./post-translation";
import { TranslateBar } from "./translate-bar";
import { useExamples } from "./use-examples";

type ExplanationPanelProps = {
  termId: string;
  /** `terms.position`: the word's tab number. */
  position: number;
  headword: string;
  surface: string;
  english: ExplanationRow | null;
  /** Already generated by an earlier click (read from the database), or null. */
  french: ExplanationRow | null;
  /** The 5 usage examples (13.2), or null for a post published before them. */
  examples: string[] | null;
  /** Their French translation, once the examples' Translate was clicked, or null. */
  examplesFr: string[] | null;
};

type View = "explanation" | "examples";

/** A swipe is at least this far sideways, and clearly more sideways than vertical. */
const SWIPE_MIN_PX = 48;

/**
 * One word's card (6.3, 8.2, 13.3, mockups 02 and 07): the header (headword,
 * flag, French equivalents) and, below it, either the explanation or the 5
 * usage examples. A small icon button next to the title switches between the
 * two; on a phone, swiping the card sideways does the same, with 2 page dots
 * under it.
 *
 * Each view has its own Translate toggle. The explanation's (8.2, F9): the
 * first click on a word without a French version asks the server, which
 * generates and stores it (Claude call #3), and the button shows "Translating…"
 * meanwhile; every later click only switches what is shown, with no request.
 * The French version is also in the page data after a reload, so a word is
 * translated once, ever (D-09). The examples' (13.2) works the same way, see
 * `useExamples()`; a post published before 13.2 gets its examples written the
 * first time its examples view is opened.
 *
 * Which words are in French is kept in the page's translation state, so the
 * post card can show the French post text (8.3) while this word's explanation
 * is on screen in French. The first Translate of the post also brings that
 * French text, with the French words of each term marked (8.4). A post
 * translated before that has its text regenerated on its next Translate, once.
 * The examples' translation doesn't touch the post card.
 *
 * Both views stay mounted (the other is hidden), so a word keeps what it shows
 * when you switch views or tabs.
 */
export function ExplanationPanel({
  termId,
  position,
  headword,
  surface,
  english,
  french: initialFrench,
  examples: initialExamples,
  examplesFr: initialExamplesFr,
}: ExplanationPanelProps) {
  const [french, setFrench] = useState(initialFrench);
  const translation = usePostTranslation();
  const showFrench = translation?.isFrench(position) ?? false;
  const setShowFrench = (shown: boolean) => translation?.setFrench(position, shown);
  const [error, setError] = useState<string | null>(null);
  const [translating, startTranslating] = useTransition();

  const [view, setView] = useState<View>("explanation");
  const examples = useExamples(termId, initialExamples, initialExamplesFr);
  const swipeStart = useRef<{ x: number; y: number } | null>(null);

  function show(next: View) {
    setView(next);
    if (next === "examples") examples.open();
  }

  function onTouchStart(event: TouchEvent) {
    const touch = event.touches[0];
    swipeStart.current =
      event.touches.length === 1 && touch ? { x: touch.clientX, y: touch.clientY } : null;
  }

  function onTouchEnd(event: TouchEvent) {
    const start = swipeStart.current;
    const touch = event.changedTouches[0];
    swipeStart.current = null;
    if (!start || !touch || !english) return;
    const dx = touch.clientX - start.x;
    const dy = touch.clientY - start.y;
    if (Math.abs(dx) < SWIPE_MIN_PX || Math.abs(dx) < Math.abs(dy) * 1.5) return;
    // Left shows the next page (the examples), right the previous one.
    show(dx < 0 ? "examples" : "explanation");
  }

  function toggle() {
    setError(null);
    if (showFrench) return setShowFrench(false);
    // A word translated before 8.4 still asks once if the post's French text has no marks yet.
    if (french && !translation?.textNeedsRefresh) return setShowFrench(true);

    startTranslating(async () => {
      let result: Awaited<ReturnType<typeof translateAction>>;
      try {
        result = await translateAction(termId);
      } catch {
        result = { ok: false, error: "The translation failed. Check your connection." };
      }
      if (result.ok) {
        setFrench(result.explanation);
        translation?.receiveTextFr(result.textFr);
        setShowFrench(true);
      } else {
        setError(result.error);
      }
    });
  }

  const examplesOpen = view === "examples";
  const toggleLabel = examplesOpen ? "Show the explanation" : "Show usage examples";

  return (
    <>
      <div
        onTouchStart={onTouchStart}
        onTouchEnd={onTouchEnd}
        onTouchCancel={() => {
          swipeStart.current = null;
        }}
        className="touch-pan-y rounded-[1.375rem] border border-line bg-surface px-4.5 py-6 sm:rounded-3xl sm:px-8 sm:py-8"
      >
        <ExplanationHeader
          headword={headword}
          explanation={english}
          action={
            english ? (
              <button
                type="button"
                onClick={() => show(examplesOpen ? "explanation" : "examples")}
                aria-pressed={examplesOpen}
                aria-label={toggleLabel}
                title={toggleLabel}
                className={`grid size-11 shrink-0 place-items-center rounded-xl border transition ${
                  examplesOpen
                    ? "border-gold-soft bg-gold-soft text-[#17140b] hover:bg-gold"
                    : "border-line-strong bg-surface-2 text-gold-soft hover:bg-surface-3"
                }`}
              >
                <NumberedListIcon size={20} />
              </button>
            ) : null
          }
        />

        <div hidden={examplesOpen}>
          <Explanation surface={surface} explanation={showFrench ? french : english} />

          {english ? (
            <TranslateBar
              showFrench={showFrench}
              translating={translating}
              error={error}
              onToggle={toggle}
            />
          ) : null}
        </div>

        {english ? (
          <div hidden={!examplesOpen}>
            <ExamplesView
              english={examples.english}
              french={examples.french}
              showFrench={examples.showFrench}
              generating={examples.generating}
              error={examples.english ? null : examples.error}
              onRetry={examples.open}
            />
            {examples.english ? (
              <TranslateBar
                showFrench={examples.showFrench}
                translating={examples.translating}
                error={examples.error}
                onToggle={examples.toggleFrench}
                compact
              />
            ) : null}
          </div>
        ) : null}
      </div>

      {english ? <PageDots view={view} onSelect={show} /> : null}
    </>
  );
}

/** The 2 pages of the card (explanation, examples) on a phone; the active one is the gold pill. */
function PageDots({ view, onSelect }: { view: View; onSelect: (view: View) => void }) {
  const pages: { view: View; label: string }[] = [
    { view: "explanation", label: "Explanation" },
    { view: "examples", label: "Usage examples" },
  ];
  return (
    <div className="mt-2 flex justify-center sm:hidden">
      {pages.map((page) => {
        const active = page.view === view;
        return (
          <button
            key={page.view}
            type="button"
            onClick={() => onSelect(page.view)}
            aria-label={page.label}
            aria-current={active}
            className="grid h-6 w-7 place-items-center"
          >
            <span
              className={`block h-1.5 rounded-full transition-all ${
                active ? "w-5 bg-gold" : "w-1.5 bg-line-strong"
              }`}
            />
          </button>
        );
      })}
    </div>
  );
}
